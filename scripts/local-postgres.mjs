import 'dotenv/config';
import EmbeddedPostgres from 'embedded-postgres';
import { existsSync } from 'node:fs';
import path from 'node:path';
const url=new URL(process.env.DATABASE_URL||'postgresql://lanka:local_dev_only@127.0.0.1:55432/lanka_table');
if(!['127.0.0.1','localhost'].includes(url.hostname)) throw new Error('db:local only starts a loopback database.');
const databaseDir=path.resolve('.local/postgres');
const pg=new EmbeddedPostgres({databaseDir,user:decodeURIComponent(url.username),password:decodeURIComponent(url.password),port:Number(url.port||55432),persistent:true,authMethod:'scram-sha-256',initdbFlags:['--encoding=UTF8','--locale=C'],postgresFlags:['-h','127.0.0.1','-k','/private/tmp'],onLog:()=>{},onError:message=>console.error(String(message).trim())});
if(!existsSync(path.join(databaseDir,'PG_VERSION'))) await pg.initialise();
await pg.start();
const client=pg.getPgClient();await client.connect();
const name=url.pathname.slice(1);
if(!/^[a-z][a-z0-9_]*$/.test(name))throw new Error('Use a simple lowercase database name.');
if(!(await client.query('SELECT 1 FROM pg_database WHERE datname=$1',[name])).rowCount)await pg.createDatabase(name);
await client.end();
console.log(`PostgreSQL ready on 127.0.0.1:${url.port}. Data persists in .local/postgres. Press Ctrl+C to stop.`);
let stopping=false;
for(const signal of ['SIGINT','SIGTERM'])process.on(signal,async()=>{if(stopping)return;stopping=true;await pg.stop();process.exit(0);});
setInterval(()=>{},60000);
